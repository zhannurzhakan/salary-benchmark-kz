# ---- salary ---------------------------------------------------------------

def to_kzt_month(sal_from, sal_to, currency, gross, cfg):
    """Return (kzt_from, kzt_to, kzt_mid, range_type) as GROSS monthly KZT, or None if unusable.
    'Net' (на руки) amounts are grossed up with the exact payroll-tax model in sbench/tax.py."""
    from . import tax
    fx = cfg["fx_to_kzt"].get((currency or "KZT").upper())
    if fx is None or (sal_from is None and sal_to is None):
        return None
    t = tax.params(cfg)

    def conv(v):
        if not v:
            return None
        v = v * fx
        return v if gross else tax.gross_from_net(v, t)
    f, t_ = conv(sal_from), conv(sal_to)
    lo, hi = cfg["sanity_bounds_kzt_month"]
    for v in (f, t_):
        if v is not None and not (lo <= v <= hi):
            return None
    if f and t_:
        if t_ < f:
            f, t_ = t_, f
        return f, t_, (f + t_) / 2, "closed"
    if f:
        return f, None, f, "from"
    return None, t_, t_, "to"


# ---- titles ---------------------------------------------------------------

_LEVEL_RULES = [
    ("Стажёр / Junior", r"стаж[её]р|intern|практикант|junior|джун|младший|помощник|ассистент"),
    ("Руководитель", r"начальник|руководитель|директор|заведующ|head of|\bhead\b|chief|управляющий|заместитель|\bCEO\b|\bCFO\b|\bCTO\b"),
    ("Senior / Ведущий", r"senior|сеньор|старший|ведущий|главный|lead\b|тимлид|team ?lead|principal"),
]
_LEVEL_STRIP = re.compile(
    r"\b(junior|senior|middle|lead|intern|джуниор|сеньор|мидл|младший|старший|ведущий|стаж[её]р)\b", re.I)


def level_of(title: str) -> str:
    for name, rx in _LEVEL_RULES:
        if re.search(rx, title or "", re.I):
            return name
    return "Middle / Специалист"


def title_norm(title: str) -> str:
    t = (title or "").lower()
    t = re.sub(r"[\(\[\{].*?[\)\]\}]", " ", t)          # (вахта), [Алматы]
    t = re.split(r"\s(?:филиал\w*|ао|тоо|ст\.|станци\w*|депо|оао|гу|кгп|рго)\b|[«\"]", t)[0]  # employer / place tails
    t = re.sub(r"\b(в|г|город|г\.)\s+[а-яёa-z\-]+$", " ", t)  # "в Алматы" tails
    t = _LEVEL_STRIP.sub(" ", t)
    t = re.sub(r"[^a-zа-яёәіңғүұқөһ0-9+#/ \-]", " ", t)
    t = re.sub(r"\s+", " ", t).strip(" -/")
    return t or (title or "").strip().lower()


