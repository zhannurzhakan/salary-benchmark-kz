def norm_region(s: str | None) -> str:
    if not s:
        return "Не указано"
    t = re.sub(r"^(г\.|город)\s*", "", s.strip(), flags=re.I)
    key = t.lower().strip()
    if key in _CITY_TO_REGION:
        return _CITY_TO_REGION[key]
    return s.strip()
