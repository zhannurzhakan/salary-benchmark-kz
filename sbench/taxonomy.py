def norm_region(s) -> str:
    if not s:
        return "Не указано"
    raw = str(s)
    t = re.sub(r"\(.*?\)", " ", raw.lower())                 # "Аксуат (Абайская область, …)" -> keep outer name
    key = re.sub(r"[^а-яёәіңғүұқөһa-z\-]", "", re.sub(r"\b(область|обл|город|г)\b\.?", "", t))
    key = key.replace("-", "")
    if key in _REGION_KEYS:
        return _REGION_KEYS[key]
    for k, v in _REGION_KEYS.items():                          # e.g. "жетысуская область" variants
        if len(k) > 5 and key.startswith(k[:9]):
            return v
    city = re.sub(r"\b(г|город)\b\.?", "", t).strip(" .,")
    city = re.sub(r"\s+", " ", city)
    if city in _CITY_TO_REGION and _CITY_TO_REGION[city]:
        return _CITY_TO_REGION[city]
    m = re.search(r"\(([^)]*)\)", raw)                          # hh sub-area: "(Абайская область, …)"
    if m:
        return norm_region(m.group(1).split(",")[0])
    return "Не указано"


