def norm_industry(name=None, hh_id=None, hint_text: str = "") -> str:
    if hh_id is not None and str(hh_id) in _HH_INDUSTRY:
        return INDUSTRIES[_HH_INDUSTRY[str(hh_id)]]
    t = (name or "").lower()
    if t:
        for stem, idx in _STAT_INDUSTRY:
            if t.startswith(stem) or re.search(r"\b" + stem, t):
                return INDUSTRIES[idx]
        if name in INDUSTRIES:
            return name
    for rx, idx in _EMPLOYER_HINTS:
        if hint_text and re.search(rx, hint_text.lower()):
            return INDUSTRIES[idx]
    return "Не указано"


# -------------------------------------------------- professional areas/roles ---
@lru_cache(maxsize=1)
def hh_catalog():
    return json.loads((DATA / "hh_roles.json").read_text(encoding="utf-8"))


def categories() -> list[str]:
    return [c["name"] for c in hh_catalog() if c["name"] != "Другое"] + ["Другое"]


def roles() -> list[tuple[str, str]]:
    """[(category, role), ...] — the position catalogue (304 roles in hh's classifier)."""
    return [(c["name"], r["name"]) for c in hh_catalog() for r in c["roles"]]


